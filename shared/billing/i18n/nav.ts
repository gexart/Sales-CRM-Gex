const DICTS: Record<SupportedLanguage, Record<string, string>> = { en: {}, hi: HI, bn: BN };

/** Label in the chosen language; falls back to English (strips a trailing "+" used for "create new"). */
export function navLabel(label: string, lang: SupportedLanguage): string {
  if (lang === 'en') return label;
  const plus = label.endsWith('+');
  const base = plus ? label.slice(0, -1) : label;
  const t = DICTS[lang][base];
  return t ? `${t}${plus ? '+' : ''}` : label;
}

