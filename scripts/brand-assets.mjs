// Regenerates every brand asset from shared/brand.ts (the single source of the hexagon G):
//   node scripts/brand-assets.mjs
// Outputs: favicons + apple-touch icon (public/), the PDF logo (worker/lib/brand-png.ts) and the
// Android adaptive-icon foregrounds (android/.../mipmap-*/ic_launcher_foreground.png).
import { mkdirSync, writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";
import { markSvg, markTileSvg } from "../shared/brand.ts";

const png = (svg, width) => new Resvg(svg, { fitTo: { mode: "width", value: width } }).render().asPng();
const inner = (svg) => svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");

// Favicon: navy mark in light browser chrome, white-navy mark in dark chrome.
const light = markTileSvg({ size: 64, pad: 0.04, uid: "fl" });
const dark = markTileSvg({ size: 64, pad: 0.04, variant: "dark", uid: "fd" });
writeFileSync(
  "public/favicon.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><style>.d{display:none}@media (prefers-color-scheme:dark){.l{display:none}.d{display:inline}}</style><g class="l">${inner(light)}</g><g class="d">${inner(dark)}</g></svg>\n`,
);
writeFileSync("public/favicon-32.png", png(markTileSvg({ size: 64, pad: 0.04, uid: "p" }), 32));
writeFileSync("public/apple-touch-icon.png", png(markTileSvg({ size: 180, pad: 0.16, bg: "#FFFFFF", uid: "a" }), 180));
mkdirSync("public/brand", { recursive: true });
writeFileSync("public/brand/gexart-mark.svg", markSvg({ uid: "bl" }) + "\n");
writeFileSync("public/brand/gexart-mark-dark.svg", markSvg({ variant: "dark", uid: "bd" }) + "\n");

// PDF cover logo (white/orange mark on the navy band).
const pdfPng = png(markTileSvg({ size: 256, pad: 0.02, variant: "dark", uid: "pdf" }), 256);
writeFileSync(
  "worker/lib/brand-png.ts",
  `// Generated by scripts/brand-assets.mjs. Do not edit.\n/** Gexart mark (dark-background variant), 256×256 PNG. */\nexport const MARK_DARK_PNG_BASE64 =\n  "${Buffer.from(pdfPng).toString("base64")}";\n`,
);

// Android adaptive icon foreground: 108dp canvas, mark kept inside the 66dp safe zone.
const densities = { mdpi: 108, hdpi: 162, xhdpi: 216, xxhdpi: 324, xxxhdpi: 432 };
for (const [d, px] of Object.entries(densities)) {
  const dir = `android/app/src/main/res/mipmap-${d}`;
  mkdirSync(dir, { recursive: true });
  writeFileSync(`${dir}/ic_launcher_foreground.png`, png(markTileSvg({ size: 432, pad: 0.24, uid: `an${d}` }), px));
}
console.log("brand assets written");
